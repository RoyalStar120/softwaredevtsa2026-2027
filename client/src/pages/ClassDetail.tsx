import { useMemo, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import {
  AlertTriangle,
  ArrowRight,
  BarChart3,
  ClipboardList,
  Download,
  FlaskConical,
  Grid3x3,
  LayoutDashboard,
  Plus,
  Trash2,
  Users,
  Copy,
  Target,
  Info,
} from 'lucide-react';
import type { ClassMistakeStat } from '../../../shared/api.ts';
import { PageHeader, Avatar } from '../components/Layout.tsx';
import { AssignModal, type AssignPreset } from '../components/AssignModal.tsx';
import { AttemptList, ModuleIcon } from '../components/domain.tsx';
import { BarList, LineChart, masteryColor } from '../components/charts.tsx';
import { Badge, Callout, Card, Empty, PageLoading, ProgressBar, Tabs, fmtAgo, fmtDate, useToast } from '../components/ui.tsx';
import { useLoad, useSession } from '../state/session.tsx';
import { api } from '../api.ts';

type TabId = 'overview' | 'mastery' | 'assignments' | 'evidence' | 'roster';

export default function ClassDetail() {
  const { id = '' } = useParams();
  const detail = useLoad(() => api.classDetail(id), [id]);
  const { catalog, skill, template } = useSession();
  const navigate = useNavigate();
  const toast = useToast();
  const [tab, setTab] = useState<TabId>('overview');
  const [assignOpen, setAssignOpen] = useState(false);
  const [preset, setPreset] = useState<AssignPreset | undefined>();

  const skillsByModule = useMemo(() => (catalog?.modules ?? []).map((m) => ({ module: m, skills: m.skills })), [catalog]);

  if (detail.loading && !detail.data) return <PageLoading />;
  if (detail.error || !detail.data) return <div className="page"><Callout tone="danger">{detail.error}</Callout></div>;
  const d = detail.data;

  const openAssign = (p?: AssignPreset) => {
    setPreset(p);
    setAssignOpen(true);
  };
  const targetMistake = (m: ClassMistakeStat) =>
    openAssign({
      title: `Targeted practice: ${m.title.toLowerCase()}`,
      focusSkills: m.skillIds,
      studentIds: m.studentIds,
      note: `SkillBridge noticed "${m.title}" in your recent work. This practice targets the skills involved.`,
    });
  const remove = async (aid: string) => {
    if (!confirm('Delete this assignment?')) return;
    await api.deleteAssignment(aid);
    detail.reload();
    toast('Assignment deleted', 'info');
  };

  const needHelp = d.roster
    .filter((r) => r.activePatterns > 0 || (r.recentScores !== null && r.recentScores < 60))
    .sort((a, b) => b.activePatterns - a.activePatterns || (a.recentScores ?? 0) - (b.recentScores ?? 0));
  const ev = d.evidence;

  return (
    <div className="page wide">
      <PageHeader
        eyebrow={<Link to="/instructor">← Classes</Link>}
        title={d.klass.name}
        subtitle={
          <span className="row gap-6 wrap">
            <span>
              {d.klass.studentCount} students · join code <b className="mono">{d.klass.code}</b>
            </span>
            <button className="btn btn-ghost btn-sm" onClick={() => { void navigator.clipboard?.writeText(d.klass.code); toast('Join code copied', 'info'); }}>
              <Copy /> Copy
            </button>
          </span>
        }
        actions={
          <>
            <a className="btn" href={api.exportUrl(d.klass.id)}>
              <Download /> Export CSV
            </a>
            <button className="btn btn-primary" onClick={() => openAssign()}>
              <Plus /> New assignment
            </button>
          </>
        }
      />
      {ev.simulatedShare > 0 && (
        <div className="sim-banner" style={{ marginBottom: 16 }}>
          <Info />
          <span>
            <b>Demo data:</b> {Math.round(ev.simulatedShare * 100)}% of this roster are <b>simulated learners</b>. Their attempts were generated by running simulated
            learners through SkillBridge's real engines to demonstrate the dashboard. They are not evidence of learning gains.
          </span>
        </div>
      )}

      <Tabs<TabId>
        tabs={[
          { id: 'overview', label: 'Overview', icon: <LayoutDashboard /> },
          { id: 'mastery', label: 'Skill mastery', icon: <Grid3x3 /> },
          { id: 'assignments', label: `Assignments (${d.assignments.length})`, icon: <ClipboardList /> },
          { id: 'evidence', label: 'Learning evidence', icon: <FlaskConical /> },
          { id: 'roster', label: 'Roster', icon: <Users /> },
        ]}
        value={tab}
        onChange={setTab}
      />

      <div className="stack-lg" style={{ marginTop: 18 }}>
        {tab === 'overview' && (
          <>
            <div className="grid grid-4">
              {[
                { l: 'Students', v: d.klass.studentCount },
                { l: 'Attempts this week', v: d.klass.attemptsThisWeek },
                { l: 'Average score', v: d.klass.avgScore ?? '-' },
                { l: 'Students with recurring mistakes', v: d.roster.filter((r) => r.activePatterns > 0).length },
              ].map((s) => (
                <div key={s.l} className="card card-pad stat">
                  <span className="stat-label">{s.l}</span>
                  <span className="stat-value">{s.v}</span>
                </div>
              ))}
            </div>
            <div className="grid grid-3">
              <Card title="Common mistakes across the class" icon={<AlertTriangle />} className="span-2">
                {d.mistakes.length === 0 ? (
                  <Empty title="No mistakes recorded yet" />
                ) : (
                  <div className="col gap-10" style={{ gap: 12 }}>
                    {d.mistakes.map((m) => (
                      <div key={m.code} className="row top gap-16">
                        <ModuleIcon moduleId={m.moduleId} size={30} />
                        <div className="grow">
                          <div className="row between gap-6">
                            <span className="bold small">{m.title}</span>
                            <span className="small muted nowrap">
                              {m.students} student{m.students === 1 ? '' : 's'} · {m.occurrences}×
                            </span>
                          </div>
                          <ProgressBar value={m.students / Math.max(1, d.klass.studentCount)} small color={m.severity === 'critical' ? 'var(--danger-500)' : m.severity === 'major' ? 'var(--warning-500)' : 'var(--info-500)'} />
                          <div className="row wrap gap-4" style={{ marginTop: 4 }}>
                            <Badge tone={m.severity === 'critical' ? 'danger' : m.severity === 'major' ? 'warning' : 'neutral'}>{m.severity}</Badge>
                            {m.skillIds.map((s) => (
                              <span key={s} className="tiny muted">
                                {skill(s)?.shortName}
                              </span>
                            ))}
                          </div>
                        </div>
                        <button className="btn btn-sm btn-soft" onClick={() => targetMistake(m)} title="Assign adaptive practice for the affected students">
                          <Target /> Target
                        </button>
                      </div>
                    ))}
                  </div>
                )}
              </Card>
              <Card title="Students who may need help" icon={<Users />}>
                {needHelp.length === 0 ? (
                  <p className="small muted">Everyone is on track.</p>
                ) : (
                  <div className="col gap-6">
                    {needHelp.slice(0, 6).map((r) => (
                      <Link key={r.user.id} to={`/instructor/students/${r.user.id}`} className="attempt-item" style={{ gridTemplateColumns: '36px 1fr auto' }}>
                        <Avatar name={r.user.displayName} />
                        <div>
                          <div className="bold small">{r.user.displayName}</div>
                          <div className="tiny muted">
                            {r.activePatterns > 0 ? `${r.activePatterns} recurring mistake${r.activePatterns > 1 ? 's' : ''}` : 'Low recent scores'} · recent avg {r.recentScores ?? '-'}
                          </div>
                        </div>
                        <ArrowRight width={16} height={16} color="var(--muted)" />
                      </Link>
                    ))}
                  </div>
                )}
              </Card>
            </div>
            <div className="grid grid-2">
              <Card title="Recent attempts" icon={<BarChart3 />}>
                {d.recentAttempts.length ? <AttemptList attempts={d.recentAttempts.slice(0, 8)} showStudent /> : <Empty title="No attempts yet" />}
              </Card>
              <Card title="Assignment progress" icon={<ClipboardList />}>
                {d.assignments.length === 0 ? (
                  <Empty title="No assignments yet" />
                ) : (
                  <BarList
                    items={d.assignments.slice(0, 6).map((a) => ({
                      id: a.id,
                      label: (
                        <span>
                          <b>{a.title}</b> {a.kind !== 'practice' && <Badge tone="info">{a.kind}</Badge>}
                        </span>
                      ),
                      value: a.completedCount,
                      max: a.assignedCount,
                      right: `${a.completedCount}/${a.assignedCount} done${a.avgScore !== null ? ` · avg ${a.avgScore}` : ''}`,
                      color: 'var(--accent)',
                    }))}
                  />
                )}
              </Card>
            </div>
          </>
        )}

        {tab === 'mastery' && (
          <Card title="Skill mastery heatmap" icon={<Grid3x3 />}>
            <div className="table-wrap">
              <table className="heatmap">
                <thead>
                  <tr>
                    <th />
                    {skillsByModule.map(({ module, skills }) => (
                      <th key={module.id} colSpan={skills.length} style={{ textAlign: 'left', color: module.id === 'electrical' ? '#c27803' : 'var(--prog)' }}>
                        {module.name.split(':')[0]}
                      </th>
                    ))}
                  </tr>
                  <tr>
                    <th />
                    {skillsByModule.flatMap(({ skills }) =>
                      skills.map((s) => (
                        <th key={s.id} className="rot">
                          <div>{s.shortName}</div>
                        </th>
                      )),
                    )}
                  </tr>
                </thead>
                <tbody>
                  {d.roster.map((r) => (
                    <tr key={r.user.id} style={{ cursor: 'pointer' }} onClick={() => navigate(`/instructor/students/${r.user.id}`)}>
                      <td className="name">{r.user.displayName}</td>
                      {skillsByModule.flatMap(({ skills }) =>
                        skills.map((s) => {
                          const v = r.skills[s.id];
                          return (
                            <td
                              key={s.id}
                              className="cell"
                              style={{ background: masteryColor(v?.mastery ?? 0, v?.evidenceCount ?? 0), color: v?.evidenceCount ? '#fff' : 'var(--muted)' }}
                              title={`${r.user.displayName} · ${s.name}: ${v?.evidenceCount ? `${Math.round(v.mastery * 100)}% (${v.level})` : 'not started'}`}
                            >
                              {v?.evidenceCount ? Math.round(v.mastery * 100) : '·'}
                            </td>
                          );
                        }),
                      )}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="row wrap gap-10 tiny muted" style={{ marginTop: 10, gap: 12 }}>
              {(['not_started', 'novice', 'developing', 'proficient', 'mastered'] as const).map((l) => (
                <span key={l} className="row gap-4">
                  <span className="dot" style={{ background: `var(--lvl-${l})` }} /> {l.replace('_', ' ')}
                </span>
              ))}
              <span>· Click a row to open the student</span>
            </div>
          </Card>
        )}

        {tab === 'assignments' && (
          <Card
            title="Assignments"
            icon={<ClipboardList />}
            actions={
              <button className="btn btn-sm btn-primary" onClick={() => openAssign()}>
                <Plus /> New
              </button>
            }
          >
            {d.assignments.length === 0 ? (
              <Empty title="No assignments yet" />
            ) : (
              <div className="table-wrap">
                <table className="table">
                  <thead>
                    <tr>
                      <th>Assignment</th>
                      <th>Type</th>
                      <th>Target</th>
                      <th>Due</th>
                      <th>Progress</th>
                      <th>Avg score</th>
                      <th />
                    </tr>
                  </thead>
                  <tbody>
                    {d.assignments.map((a) => (
                      <tr key={a.id}>
                        <td>
                          <div className="bold">{a.title}</div>
                          <div className="tiny muted">
                            {a.templateId ? template(a.templateId)?.title : `Skills: ${a.focusSkills.map((s) => skill(s)?.shortName ?? s).join(', ')}`}
                            {a.difficulty ? ` · difficulty ${a.difficulty}` : ''}
                          </div>
                        </td>
                        <td>
                          <Badge tone={a.kind === 'practice' ? 'neutral' : 'info'}>{a.kind}</Badge>
                        </td>
                        <td className="small">{a.targetUserId ? d.roster.find((r) => r.user.id === a.targetUserId)?.user.displayName ?? 'Student' : 'Whole class'}</td>
                        <td className="small">{fmtDate(a.dueAt)}</td>
                        <td style={{ minWidth: 140 }}>
                          <ProgressBar value={a.completedCount / Math.max(1, a.assignedCount)} small color="var(--accent)" />
                          <div className="tiny muted" style={{ marginTop: 3 }}>
                            {a.completedCount}/{a.assignedCount} complete{a.inProgressCount ? ` · ${a.inProgressCount} in progress` : ''}
                          </div>
                        </td>
                        <td className="bold">{a.avgScore ?? '-'}</td>
                        <td>
                          <button className="btn btn-ghost btn-icon btn-sm" onClick={() => remove(a.id)} aria-label="Delete assignment">
                            <Trash2 />
                          </button>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </Card>
        )}

        {tab === 'evidence' && (
          <>
            <Callout tone="info" title="Measuring whether SkillBridge helps, honestly">
              Compare a <b>baseline</b> assessment with a <b>transfer</b> assessment: a different scenario that measures the same skills. Also track whether mistakes
              decline across attempts. Report the sample size and limitations, and don't claim improvement until you have collected real data.
            </Callout>
            <div className="grid grid-4">
              <div className="card card-pad stat">
                <span className="stat-label">Baseline average</span>
                <span className="stat-value">{ev.baselineAvg ?? '-'}</span>
                <span className="stat-sub">n = {ev.prePost.length}</span>
              </div>
              <div className="card card-pad stat">
                <span className="stat-label">Transfer average</span>
                <span className="stat-value">{ev.transferAvg ?? '-'}</span>
                <span className="stat-sub">different scenario, same skills</span>
              </div>
              <div className="card card-pad stat">
                <span className="stat-label">Recurring patterns resolved</span>
                <span className="stat-value">
                  {ev.patternsResolved}/{ev.patternsTotal}
                </span>
                <span className="stat-sub">mistakes that stopped recurring</span>
              </div>
              <div className="card card-pad stat">
                <span className="stat-label">Sample</span>
                <span className="stat-value">{ev.sampleSize}</span>
                <span className="stat-sub">{ev.simulatedShare > 0 ? `${Math.round(ev.simulatedShare * 100)}% simulated` : 'real students'}</span>
              </div>
            </div>
            <div className="grid grid-2">
              <Card title="Baseline vs. transfer, per student">
                {ev.prePost.length === 0 ? (
                  <Empty title="No paired assessments yet">Assign a baseline and a transfer test to compare.</Empty>
                ) : (
                  <div className="col gap-6">
                    {ev.prePost.map((p) => (
                      <div key={p.userId} className="row gap-10" style={{ gap: 10 }}>
                        <span className="small bold" style={{ width: 120, flex: 'none' }}>
                          {p.name}
                        </span>
                        <div className="grow" style={{ position: 'relative', height: 22 }}>
                          <div style={{ position: 'absolute', inset: '9px 0', background: 'var(--surface-3)', borderRadius: 3 }} />
                          <div style={{ position: 'absolute', left: `${Math.min(p.baseline, p.transfer)}%`, width: `${Math.abs(p.transfer - p.baseline)}%`, top: 9, height: 4, background: p.transfer >= p.baseline ? 'var(--success-500)' : 'var(--danger-500)' }} />
                          <span title={`Baseline ${p.baseline}`} style={{ position: 'absolute', left: `calc(${p.baseline}% - 6px)`, top: 5, width: 12, height: 12, borderRadius: 6, background: 'var(--muted)' }} />
                          <span title={`Transfer ${p.transfer}`} style={{ position: 'absolute', left: `calc(${p.transfer}% - 6px)`, top: 5, width: 12, height: 12, borderRadius: 6, background: 'var(--primary)' }} />
                        </div>
                        <span className="small nowrap" style={{ width: 70, textAlign: 'right' }}>
                          {p.baseline} → <b>{p.transfer}</b>
                        </span>
                      </div>
                    ))}
                    <div className="row gap-16 tiny muted" style={{ marginTop: 6 }}>
                      <span className="row gap-4">
                        <span className="dot" style={{ background: 'var(--muted)' }} /> Baseline
                      </span>
                      <span className="row gap-4">
                        <span className="dot" style={{ background: 'var(--primary)' }} /> Transfer
                      </span>
                    </div>
                  </div>
                )}
              </Card>
              <Card title="Error reduction across attempts">
                <LineChart
                  height={230}
                  yMin={0}
                  series={[
                    { id: 'mistakes', label: 'Avg mistakes on Nth attempt', color: '#ef4444', points: ev.mistakesByAttemptIndex.map((p) => ({ x: p.index, y: p.avgMistakes, label: `${p.avgMistakes} (n=${p.n})` })) },
                  ]}
                  xFormat={(v) => `#${Math.round(v)}`}
                  yFormat={(v) => v.toFixed(1)}
                  emptyText="Not enough attempts yet."
                />
                <p className="tiny muted" style={{ marginTop: 6 }}>
                  Average number of evaluator-detected mistakes on each student's 1st, 2nd, 3rd… attempt. Later points include fewer students (n shown on hover). Difficulty
                  rises as students improve, so this is a conservative measure.
                </p>
              </Card>
            </div>
            <Card title="Limitations to report">
              <ul className="small text-2" style={{ margin: 0, paddingLeft: 18 }}>
                <li>Small samples: one class is not enough to generalize.</li>
                <li>No control group: improvement may come from any practice, not specifically from SkillBridge's adaptivity.</li>
                <li>Retention: delayed re-testing (for example, one week later) is needed to show learning lasts.</li>
                <li>Simulation fidelity: simulated tasks approximate, but do not equal, real-world performance or certification.</li>
              </ul>
              <a className="btn btn-sm" style={{ marginTop: 12 }} href={api.exportUrl(d.klass.id)}>
                <Download /> Export attempt-level data (CSV)
              </a>
            </Card>
          </>
        )}

        {tab === 'roster' && (
          <Card title="Roster" icon={<Users />}>
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th>Student</th>
                    <th>Completed</th>
                    <th>Avg score</th>
                    <th>First → recent</th>
                    <th>Recurring mistakes</th>
                    <th>Last active</th>
                  </tr>
                </thead>
                <tbody>
                  {d.roster.map((r) => {
                    const delta = r.firstScores !== null && r.recentScores !== null ? r.recentScores - r.firstScores : null;
                    return (
                      <tr key={r.user.id} className="clickable" onClick={() => navigate(`/instructor/students/${r.user.id}`)}>
                        <td>
                          <div className="row gap-6">
                            <Avatar name={r.user.displayName} />
                            <span className="bold">{r.user.displayName}</span>
                            {r.user.isDemo && <Badge tone="primary">demo</Badge>}
                          </div>
                        </td>
                        <td>{r.completed}</td>
                        <td className="bold">{r.avgScore ?? '-'}</td>
                        <td className="small">
                          {r.firstScores ?? '-'} → {r.recentScores ?? '-'}{' '}
                          {delta !== null && (
                            <span className={delta >= 0 ? 'delta-up' : 'delta-down'}>
                              ({delta >= 0 ? '+' : ''}
                              {delta})
                            </span>
                          )}
                        </td>
                        <td>{r.activePatterns > 0 ? <Badge tone="danger">{r.activePatterns} active</Badge> : <span className="muted small">none</span>}</td>
                        <td className="small muted">{fmtAgo(r.lastActiveAt)}</td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </Card>
        )}
      </div>

      <AssignModal open={assignOpen} onClose={() => setAssignOpen(false)} classId={d.klass.id} roster={d.roster} preset={preset} onCreated={detail.reload} />
    </div>
  );
}
